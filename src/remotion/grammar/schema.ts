import { z } from "zod";

// The director contract: the LLM emits THIS. It never writes animation code.
// 6 archetypes v1 (research: ship 6 perfect, keep the rest as stubs later).

export const GrammarBrand = z.object({
  name: z.string(),
  domain: z.string(),
  colors: z.object({
    bg: z.string(), // canvas (e.g. editorial cream)
    fg: z.string(), // ink
    accent: z.string(),
    muted: z.string(),
  }),
});

const ColdOpen = z.object({
  type: z.literal("COLD_OPEN"),
  vo: z.string().default("").describe("narration line for this scene — written story, not screen text"),
  variant: z.enum(["word_per_beat", "marquee", "terminal", "search"]).default("word_per_beat"),
  // search: a Google-style search bar types the pain query, ENTER slams, results reveal
  query: z.string().default("").describe("search variant: the query a desperate user would type"),
  // word_per_beat: one word per beat, last accent word explodes through camera
  // marquee: the phrase as one giant line sliding across the frame (ListenLabs)
  // terminal: a console window types the hook with keystroke sounds (Browserbase)
  words: z.array(z.object({ t: z.string(), accent: z.boolean() })).min(2).max(6),
  kicker: z.string().describe("tiny uppercase context line"),
});

const PainTypography = z.object({
  type: z.literal("PAIN_TYPOGRAPHY"),
  vo: z.string().default("").describe("narration line for this scene — written story, not screen text"),
  variant: z.enum(["circle_swap", "strike_list"]).default("circle_swap"),
  label: z.string(),
  lines: z.array(z.string()).min(2).max(3),
});

const ProductHero = z.object({
  type: z.literal("PRODUCT_HERO"),
  vo: z.string().default("").describe("narration line for this scene — written story, not screen text"),
  variant: z.enum(["window_slam", "bento", "phone"]).default("window_slam"),
  headline: z.string().describe('e.g. "Meet Leadverse." — accent goes on the substring after |'),
  screenshot: z.string().describe("staticFile path"),
  extraShots: z.array(z.string()).max(2).default([]).describe("bento variant: 2 more shots"),
  chip: z.string(),
});

const FeatureWalk = z.object({
  type: z.literal("FEATURE_WALK"),
  vo: z.string().default("").describe("narration line for this scene — written story, not screen text"),
  steps: z
    .array(z.object({ screenshot: z.string(), title: z.string() }))
    .min(2)
    .max(3),
});

const StatCallout = z.object({
  type: z.literal("STAT_CALLOUT"),
  vo: z.string().default("").describe("narration line for this scene — written story, not screen text"),
  variant: z.enum(["odometer", "repeat_stack", "slot"]).default("odometer"),
  value: z.number().describe("REAL number from the site — never invented"),
  prefix: z.string().default("").describe('e.g. "$" or ""'),
  suffix: z.string().describe('e.g. "businesses already listening"'),
});

const CtaCompression = z.object({
  type: z.literal("CTA_COMPRESSION"),
  vo: z.string().default("").describe("narration line for this scene — written story, not screen text"),
  headline: z.string(),
  domain: z.string(),
  sub: z.string(),
});

export const SceneSchema = z.discriminatedUnion("type", [
  ColdOpen,
  PainTypography,
  ProductHero,
  FeatureWalk,
  StatCallout,
  CtaCompression,
]);

// Canonical 16-bar sequence (bars @120BPM): fixed v1 rhythm per archetype.
export const ARCHETYPE_BARS: Record<string, number> = {
  COLD_OPEN: 2,
  PAIN_TYPOGRAPHY: 2,
  PRODUCT_HERO: 3,
  FEATURE_WALK: 4,
  STAT_CALLOUT: 2,
  CTA_COMPRESSION: 3,
};

export const FilmSchema = z.object({
  brand: GrammarBrand,
  stylePack: z.enum(["editorial_cream", "dark_terminal"]).default("editorial_cream"),
  music: z.enum(["pulse", "heavy", "adrenaline"]).default("pulse"),
  // voiceover clips (one per scene, generated by scripts/voiceover.mjs) — public/ paths
  voTracks: z.array(z.string().nullable()).default([]),
  voDurations: z.array(z.number().nullable()).default([]).describe("seconds per voTracks clip — Sequence must not outlive this or Remotion/Gemini repeats"),
  // single continuous narration (voiceover-full.mjs) — takes precedence over voTracks
  voFull: z.string().nullable().default(null),
  // Lyria-generated track (gen-music.mjs) — takes precedence over synth beds
  musicFile: z.string().nullable().default(null),
  sfx: z.boolean().default(true),
  scenes: z.array(SceneSchema).min(4).max(8),
});

export const STYLE_PACKS: Record<string, { bg: string; fg: string; muted: string }> = {
  editorial_cream: { bg: "#F4EFE4", fg: "#101010", muted: "#8A867A" },
  dark_terminal: { bg: "#0B0B0D", fg: "#F2F0EA", muted: "#71716B" },
};

export type Film = z.infer<typeof FilmSchema>;
export type Scene = z.infer<typeof SceneSchema>;

